create or replace function public.is_public_product(target_product_id text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public."Products" as product
    left join public.categorias as category
      on category.id = product.caja
      and category."storeId" = product."storeId"
    where product."productId" = target_product_id
      and product.visible is true
      and (product.publish_at is null or product.publish_at <= now())
      and public.is_public_store(product."storeId")
      and (
        product.caja is null
        or (
          category.active is true
          and (
            category.premium is not true
            or public.has_premium_store_access(product."storeId")
          )
        )
      )
  );
$$;

create or replace function public.can_manage_user(target_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select (select auth.uid()) is not null
    and (
      public.is_platform_admin()
      or exists (
        select 1
        from public.store_members as target_membership
        join public.store_members as actor_membership
          on actor_membership.store_id = target_membership.store_id
        where target_membership.user_id = target_user_id
          and target_membership.active is true
          and actor_membership.user_id = (select auth.uid())
          and actor_membership.active is true
          and actor_membership.store_role in ('owner', 'admin')
      )
      or exists (
        select 1
        from public."Sitios" as target_store
        where target_store."Editor" = target_user_id
          and public.has_store_role(
            target_store."UUID",
            array['owner', 'admin']::text[]
          )
      )
    );
$$;

