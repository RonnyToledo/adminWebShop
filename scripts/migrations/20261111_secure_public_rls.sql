create or replace function public.is_platform_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public."user" as account
    where account.id = (select auth.uid())
      and account.role = 'admin'
  );
$$;

create or replace function public.has_store_role(
  target_store_id uuid,
  allowed_roles text[]
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select (select auth.uid()) is not null
    and (
      public.is_platform_admin()
      or exists (
        select 1
        from public."Sitios" as store
        where store."UUID" = target_store_id
          and store."Editor" = (select auth.uid())
      )
      or exists (
        select 1
        from public.store_members as membership
        where membership.store_id = target_store_id
          and membership.user_id = (select auth.uid())
          and membership.active is true
          and membership.store_role = any(coalesce(allowed_roles, '{}'::text[]))
      )
    );
$$;

