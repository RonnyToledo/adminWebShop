create or replace function public.guard_user_security_fields()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if public.is_platform_admin() then
    return new;
  end if;

  if tg_op = 'INSERT' then
    if new.role = 'admin' or coalesce(new.owner_aproved, false) then
      raise exception 'Only a platform administrator may create privileged user fields';
    end if;
    return new;
  end if;

  if old.role = 'admin' or new.role = 'admin' then
    raise exception 'Only a platform administrator may change the platform admin role';
  end if;

  if new.email is distinct from old.email
    or new.premium_catalogs is distinct from old.premium_catalogs
  then
    raise exception 'Only a platform administrator may change protected user fields';
  end if;

  if new.role is distinct from old.role
    and not public.can_manage_user(new.id)
  then
    raise exception 'Only a store owner or administrator may change a team role';
  end if;

  if new.owner_aproved is distinct from old.owner_aproved
    and not (
      new.owner_aproved is true
      and exists (
        select 1
        from public."Sitios" as store
        where store."Editor" = new.id
          and public.has_store_role(
            store."UUID",
            array['owner', 'admin']::text[]
          )
      )
    )
  then
    raise exception 'Only an authorized owner transfer may change owner approval';
  end if;

  return new;
end;
$$;

create or replace function public.guard_store_security_fields()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  plan_features record;
begin
  if public.is_platform_admin() then
    return new;
  end if;

  if tg_op = 'INSERT' then
    if new."Editor" is distinct from (select auth.uid()) then
      raise exception 'A store must be created for the authenticated owner';
    end if;
    if new.plan_vence is not null
      or new.verified is true
      or (
        new.plan is not null
        and not exists (
          select 1
          from public.plan_config as config
          where config.id = new.plan
            and coalesce(config.precio_mensual, 0) <= 0
        )
      )
    then
      raise exception 'Only a platform administrator may grant a paid plan or verification';
    end if;
  else
    if new.plan is distinct from old.plan
      or new.plan_vence is distinct from old.plan_vence
    then
      raise exception 'Only a platform administrator may change a store plan';
    end if;

    if new.verified is distinct from old.verified
      or new.verification_score is distinct from old.verification_score
      or new.verified_at is distinct from old.verified_at
      or new.verification_notice_key is distinct from old.verification_notice_key
      or new.verification_notified_at is distinct from old.verification_notified_at
    then
      raise exception 'Only a platform administrator may change store verification';
    end if;

    if new."Editor" is distinct from old."Editor"
      and old."Editor" is distinct from (select auth.uid())
    then
      raise exception 'Only the current store owner may transfer ownership';
    end if;
  end if;

  if tg_op = 'INSERT'
    or new.marketing is distinct from old.marketing
    or new.stocks is distinct from old.stocks
    or new.domicilio is distinct from old.domicilio
    or new.carrito is distinct from old.carrito
  then
    if new.plan is not null then
      select config.marketing, config.stocks, config.domicilio, config.carrito
        into plan_features
      from public.plan_config as config
      where config.id = new.plan;

      if not found
        or (new.marketing is true and plan_features.marketing is not true)
        or (new.stocks is true and plan_features.stocks is not true)
        or (new.domicilio is true and plan_features.domicilio is not true)
        or (new.carrito is true and plan_features.carrito is not true)
      then
        raise exception 'Store features must be included in the assigned plan';
      end if;
    elsif coalesce(new.marketing, false)
      or coalesce(new.stocks, false)
      or coalesce(new.domicilio, false)
      or coalesce(new.carrito, false)
    then
      raise exception 'Store features require a configured plan';
    end if;
  end if;

  return new;
end;
$$;

do $$
declare
  target_signature text;
  guard_sql text;
  config_sql text;
  function_definition text;
  begin_position integer;
  guard_position integer;
begin
  for target_signature, guard_sql in
    select * from (values
      (
        'public.activar_plan(uuid,text,uuid,text)',
        'if not public.is_platform_admin() or p_admin_id is distinct from auth.uid() then raise exception ''Only the authenticated platform administrator may activate plans''; end if;'
      ),
      (
        'public.create_sitio(text,text,text,text,text,text,boolean,bigint,text,text,boolean,jsonb,text,boolean,boolean)',
        'if auth.uid() is null or (_editor is distinct from auth.uid()::text and not public.is_platform_admin()) then raise exception ''A store may only be created for the authenticated user or by a platform administrator''; end if;'
      ),
      (
        'public.add_premium_member(uuid,uuid)',
        'if not public.has_store_role(p_store_id, array[''owner'', ''admin'']::text[]) then raise exception ''Only a store owner or administrator may manage premium members''; end if;'
      ),
      (
        'public.get_premium_members(uuid)',
        'if not public.has_store_role(p_store_id, array[''owner'', ''admin'']::text[]) then raise exception ''Only a store owner or administrator may view premium members''; end if;'
      ),
      (
        'public.set_premium_member_status(uuid,uuid,boolean)',
        'if not public.has_store_role(p_store_id, array[''owner'', ''admin'']::text[]) then raise exception ''Only a store owner or administrator may manage premium members''; end if;'
      ),
      (
        'public.search_store_customers(uuid,text)',
        'if not public.has_store_role(p_store_id, array[''owner'', ''admin'']::text[]) then raise exception ''Only a store owner or administrator may search customers''; end if;'
      ),
      (
        'public.update_visits_manual(text,integer,jsonb)',
        'if not exists (select 1 from public."Sitios" as store where store.sitioweb = p_sitioweb and public.has_store_role(store."UUID", array[''owner'', ''admin'']::text[])) then raise exception ''Only a store owner or administrator may update visits''; end if;'
      )
    ) as guards(signature, guard)
  loop
    if to_regprocedure(target_signature) is null then
      raise exception 'Expected security function % was not found', target_signature;
    end if;

    select pg_get_functiondef(to_regprocedure(target_signature))
      into function_definition;

    if target_signature = 'public.activar_plan(uuid,text,uuid,text)' then
      function_definition := replace(
        function_definition,
        '- Obtener plan actual',
        '-- Obtener plan actual'
      );
      config_sql := E'\n  select * into v_config\n  from public.plan_config\n  where id = p_plan;\n  if not found then\n    raise exception ''Plan no encontrado: %'', p_plan;\n  end if;\n';
    else
      config_sql := null;
    end if;

    begin_position := strpos(function_definition, 'BEGIN');
    if begin_position = 0 then
      raise exception 'Could not locate function body for %', target_signature;
    end if;

    if position(guard_sql in function_definition) = 0 then
      function_definition := overlay(
        function_definition
        placing E'\n  ' || guard_sql || E'\n'
        from begin_position + length('BEGIN')
        for 0
      );
    end if;

    if config_sql is not null
      and position('select * into v_config' in lower(function_definition)) = 0
    then
      guard_position := strpos(function_definition, guard_sql);
      if guard_position = 0 then
        raise exception 'Could not locate authorization guard in %', target_signature;
      end if;

      function_definition := overlay(
        function_definition
        placing config_sql
        from guard_position + length(guard_sql)
        for 0
      );
    end if;

    execute function_definition;
  end loop;

  select pg_get_functiondef(
    to_regprocedure(
      'public.update_event_adjust_stock_v3(uuid,text,jsonb,uuid,text,bigint,text,timestamptz)'
    )
  )
    into function_definition;

  if position('s."Editor" = auth.uid()::uuid' in function_definition) = 0 then
    raise exception 'The expected ownership guard in update_event_adjust_stock_v3 was not found';
  end if;

  function_definition := replace(
    function_definition,
    's."Editor" = auth.uid()::uuid',
    'public.has_store_role(v_store, ARRAY[''owner'', ''admin'', ''editor'']::text[])'
  );
  execute function_definition;
end;
$$;

